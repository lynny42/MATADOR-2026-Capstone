def _pwr(history_id: int, updated_at: str, channels: list[dict]) -> dict:
    return {"HISTORY_ID": history_id, "UPDATED_AT": updated_at, "channels": channels}


def _ch(
    sw_id: int,
    voltage: float,
    prev_voltage: float,
    current_a: float,
    prev_delta_v: float,
    curr_delta_v: float,
    exceed_count: int,
    consecutive_exceed: int,
    anomaly_flag: int,
    lo: float,
    hi: float,
) -> dict:
    return {
        "SW_ID": sw_id,
        "VOLTAGE": voltage,
        "PREV_VOLTAGE": prev_voltage,
        "CURRENT_A": current_a,
        "PREV_DELTA_V": prev_delta_v,
        "CURR_DELTA_V": curr_delta_v,
        "EXCEED_COUNT": exceed_count,
        "CONSECUTIVE_EXCEED": consecutive_exceed,
        "ANOMALY_FLAG": anomaly_flag,
        "V_THRESHOLD_LO": lo,
        "V_THRESHOLD_HI": hi,
    }


def _event(
    event_id: int,
    detected_at: str,
    event_type: str,
    weight: int,
    sw_id: int,
    channel1: int,
    *,
    priority: int = 0,
    exception_code: int = 0,
    module_scores: str = "",
    child_queue_count: int | None = None,
    file_write_err: int = 0,
    cmd_rejected: int = 0,
) -> dict:
    return {
        "packet_type": "SAT_EVENT_QUEUE",
        "event": {
            "EVENT_ID": event_id,
            "DETECTED_AT": detected_at,
            "PIPEOVERFLOWRRCNT": 0,
            "CHILDQUEUECOUNT": child_queue_count if child_queue_count is not None else event_id,
            "FILEWRITEERRCOUNTER": file_write_err,
            "CMDREJECTEDCOUNTER": cmd_rejected,
            "CH1_CH2_FAULT_CRC": 0,
            "CH1_FAULT_FILE_SIZE_MISMATCH": 0,
            "PROCESSOR_RESET_COUNT": 0,
            "IS_SENT": 0,
            "TIMESTAMP": detected_at,
            "PRIORITY": priority,
            "EVENT_TYPE": event_type,
            "SW_ID": sw_id,
            "WEIGHT": weight,
            "EXCEPTION_CODE": exception_code,
            "MODULE_SCORES": module_scores,
            "CHENNEL1": channel1,
        },
    }


